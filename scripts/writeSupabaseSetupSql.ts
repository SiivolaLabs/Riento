import { readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const rootDir = resolve(scriptDir, "..");
const outputPath = resolve(rootDir, "supabase/setup_all.sql");

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});

async function main() {
  const schema = await readFile(resolve(rootDir, "supabase/schema.sql"), "utf8");
  const seed = await readFile(resolve(rootDir, "supabase/seed_venues.sql"), "utf8");
  const launchHardening = await readFile(resolve(rootDir, "supabase/launch_hardening_final.sql"), "utf8");
  const schedule = await readFile(resolve(rootDir, "supabase/schedule_crowd_snapshots.sql"), "utf8");

  const contents = [
    "-- Generated by npm run setup:supabase:sql.",
    "-- Run this in the Supabase SQL editor for the Mesta project.",
    "-- It creates the schema, seeds venues, applies final launch hardening, and schedules maintenance jobs.",
    "",
    "begin;",
    "",
    section("schema.sql", schema),
    section("seed_venues.sql", seed),
    section("launch_hardening_final.sql", launchHardening),
    "",
    "commit;",
    "",
    "-- The schedule is outside the transaction because extension/cron setup can require separate execution.",
    section("schedule_crowd_snapshots.sql", schedule)
  ].join("\n");

  if (process.argv.includes("--check")) {
    const currentContents = await readFile(outputPath, "utf8").catch(() => "");

    if (currentContents !== contents) {
      throw new Error("supabase/setup_all.sql is stale. Run npm run setup:supabase:sql.");
    }

    console.log("supabase/setup_all.sql matches its source SQL files.");
    return;
  }

  await writeFile(outputPath, contents);
  console.log(`Wrote combined Supabase setup SQL to ${outputPath}`);
}

function section(name: string, contents: string) {
  return [`-- >>> ${name}`, contents.trim(), `-- <<< ${name}`].join("\n");
}
