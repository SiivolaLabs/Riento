import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { venueSeeds } from "../src/data/venues";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const outputPath = resolve(scriptDir, "../supabase/seed_venues.sql");

const columns = [
  "slug",
  "name",
  "kind",
  "address",
  "neighborhood",
  "latitude",
  "longitude",
  "capacity_estimate",
  "source",
  "source_external_id",
  "source_checked_at",
  "verification_status",
  "opening_hours",
  "vibe",
  "sound_tags"
];

const rows = venueSeeds.map((venue) => {
  const values = [
    sqlString(venue.id),
    sqlString(venue.name),
    sqlString(venue.kind),
    sqlString(venue.address),
    sqlString(venue.neighborhood),
    sqlNumber(venue.latitude),
    sqlNumber(venue.longitude),
    sqlNumber(venue.capacityEstimate),
    sqlString(venue.dataSource),
    sqlNullableString(venue.sourceExternalId),
    sqlNullableString(venue.sourceCheckedAt),
    sqlString(venue.verificationStatus),
    sqlJson(venue.openingHours ?? {}),
    sqlString(venue.vibe),
    sqlTextArray(venue.soundTags)
  ];

  return `  (${values.join(", ")})`;
});

const contents = `-- Generated by npm run seed:venues:sql.
-- Strong OSM matches verify source metadata only; operating status remains operator-reviewed.

insert into public.venues (${columns.join(", ")})
values
${rows.join(",\n")}
on conflict (slug) do update set
  name = excluded.name,
  kind = excluded.kind,
  address = excluded.address,
  neighborhood = excluded.neighborhood,
  latitude = excluded.latitude,
  longitude = excluded.longitude,
  capacity_estimate = excluded.capacity_estimate,
  source = excluded.source,
  source_external_id = excluded.source_external_id,
  source_checked_at = excluded.source_checked_at,
  verification_status = excluded.verification_status,
  opening_hours = excluded.opening_hours,
  vibe = excluded.vibe,
  sound_tags = excluded.sound_tags,
  updated_at = now()
where public.venues.verification_status = 'needs_verification';
`;

main().catch((error: unknown) => {
  console.error(error);
  process.exit(1);
});

async function main() {
  if (process.argv.includes("--check")) {
    const currentContents = await readFile(outputPath, "utf8").catch(() => "");

    if (currentContents !== contents) {
      throw new Error("supabase/seed_venues.sql is out of date. Run npm run seed:venues:sql.");
    }

    console.log("supabase/seed_venues.sql matches src/data/venues.ts");
    return;
  }

  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, contents);

  console.log(`Wrote ${venueSeeds.length} venues to ${outputPath}`);
}

function sqlString(value: string) {
  return `'${value.replaceAll("'", "''")}'`;
}

function sqlNumber(value: number) {
  return Number.isFinite(value) ? String(value) : "null";
}

function sqlNullableString(value: string | undefined) {
  return value ? sqlString(value) : "null";
}

function sqlJson(value: object) {
  return `${sqlString(JSON.stringify(value))}::jsonb`;
}

function sqlTextArray(values: string[]) {
  return `array[${values.map(sqlString).join(", ")}]::text[]`;
}
