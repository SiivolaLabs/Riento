export const venueSeeds: VenueSeed[] = venueSeedInputs.map((venue) => {
  const sourceMetadata = venueSourceMetadata[venue.id];

  return {
    ...venue,
    ...sourceMetadata,
    soundTags: reviewedVenueSoundTags[venue.id] ?? deriveVenueSoundTags(venue.vibe)
  };
});

export const venues: Venue[] = venueSeeds
  .filter(isActiveVenueSeed)
  .map((venue) => ({
    ...venue,
    crowdLevel: getCrowdLevel(0),
    hasLiveCrowdSignal: false,
    isRemote: false,
    lastUpdated: "No live signal",
    mockActivityScore: 0,
    openingHoursSummary: getVenueOpenStateLabel(venue.openingHours),
    slug: venue.id
  }));

function isActiveVenueSeed(venue: VenueSeed) {
  return venue.verificationStatus === "needs_verification" || venue.verificationStatus === "verified";
}
